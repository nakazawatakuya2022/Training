-- データベース作成
IF NOT EXISTS (
    SELECT name 
    FROM master.dbo.sysdatabases 
    WHERE name = 'Umineko'
)
BEGIN
    CREATE DATABASE Umineko;
END
GO

USE Umineko
GO

-- 貸出履歴
-- * BackupToTempTable
DROP TABLE IF EXISTS lent_histories;

-- * RestoreFromTempTable
CREATE TABLE lent_histories (
  member_code varchar(10) NOT NULL
  , book_id int NOT NULL
  , lent_date date NOT NULL
  , return_date date NOT NULL
  , memo nvarchar(200)
  , has_returned tinyint NOT NULL
  , CONSTRAINT lent_histories_PKC PRIMARY KEY (member_code,book_id,lent_date)
) ;

-- 会員テーブル
-- * BackupToTempTable
DROP TABLE IF EXISTS members;

-- * RestoreFromTempTable
CREATE TABLE members (
  member_code varchar(10) NOT NULL
  , member_name nvarchar(50) NOT NULL
  , member_kana nvarchar(50) NOT NULL
  , gender tinyint NOT NULL
  , zip_code varchar(8) NOT NULL
  , address1 nvarchar(100) NOT NULL
  , address2 nvarchar(100)
  , tel varchar(20) NOT NULL
  , email varchar(50)
  , memo nvarchar(200)
  , input_date date NOT NULL
  , CONSTRAINT members_PKC PRIMARY KEY (member_code)
) ;

-- 職員
-- * BackupToTempTable
DROP TABLE IF EXISTS staffs;

-- * RestoreFromTempTable
CREATE TABLE staffs (
  staff_id varchar(8) NOT NULL
  , staff_name nvarchar(20) NOT NULL
  , password varchar(8) NOT NULL
  , role tinyint NOT NULL
  , CONSTRAINT staffs_PKC PRIMARY KEY (staff_id)
) ;

-- 蔵書テーブル
-- * BackupToTempTable
DROP TABLE IF EXISTS books;

-- * RestoreFromTempTable
CREATE TABLE books (
  book_id int identity NOT NULL
  , isbn varchar(17) NOT NULL
  , title nvarchar(100) NOT NULL
  , author nvarchar(30) NOT NULL
  , publisher nvarchar(30) NOT NULL
  , purchase_date date NOT NULL
  , purchase_price int NOT NULL
  , memo nvarchar(200)
  , category_id int NOT NULL
  , lent_flag tinyint NOT NULL
  , CONSTRAINT books_PKC PRIMARY KEY (book_id)
) ;

-- カテゴリテーブル
-- * BackupToTempTable
DROP TABLE IF EXISTS categories;

-- * RestoreFromTempTable
CREATE TABLE categories (
  category_id int identity NOT NULL
  , category_name nvarchar(20) NOT NULL
  , CONSTRAINT categories_PKC PRIMARY KEY (category_id)
) ;

